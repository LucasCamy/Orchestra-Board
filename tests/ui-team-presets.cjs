  assert.equal(fs.readFileSync(conflictFile, 'utf8'), merged);
  await click('.worker-history-preview .dialog-actions button:first-child');
  await click('.worker-history-preview-undo:enabled');
  await click('.worker-history-confirm-group');
  await until("document.querySelector('.worker-review-feedback')?.textContent.includes('Batches undone in whole or in part: 2')");
  assert.equal(fs.readFileSync(conflictFile, 'utf8'), 'host changed again\n');
  assert.equal(fs.readFileSync(historyFile, 'utf8'), 'original second file\n');

