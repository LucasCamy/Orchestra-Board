  await click('.worker-history-confirm-group');
  await until("document.querySelector('.worker-review-feedback')?.textContent.includes('Batches redone in whole or in part: 2')");
  assert.equal(fs.readFileSync(conflictFile, 'utf8'), merged);
  assert.equal(fs.readFileSync(historyFile, 'utf8'), 'second batch\n');
  assert.equal(fs.readFileSync(path.join(projectC, 'review-fixture.js'), 'utf8'), 'later edit to keep\n');
